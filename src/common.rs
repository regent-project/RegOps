pub fn ensure_directory_exists(path: &str) {
    let path_obj = Path::new(path);
    if let Some(parent) = path_obj.parent() {
        if !parent.as_os_str().is_empty() {
            if let Err(e) = std::fs::create_dir_all(parent) {
                error!("Failed to create directory {}: {}", parent.display(), e);
                std::process::exit(1);
            }
        }
    }
}

#[derive(Debug, Deserialize, Serialize, Copy, Clone, PartialEq, Eq, PartialOrd, Ord, ValueEnum)]
pub enum LogFormat {
    Raw,
    Json,
}

#[derive(Debug, Deserialize, Serialize, Copy, Clone, PartialEq, Eq, PartialOrd, Ord, ValueEnum)]
pub enum LogLevel {
    Trace,
    Debug,
    Info,
    Warn,
    Error,
}

impl LogLevel {
    pub fn to_tracing_level(&self) -> LevelFilter {
        match self {
            LogLevel::Trace => LevelFilter::TRACE,
            LogLevel::Debug => LevelFilter::DEBUG,
            LogLevel::Info => LevelFilter::INFO,
            LogLevel::Warn => LevelFilter::WARN,
            LogLevel::Error => LevelFilter::ERROR,
        }
    }
}

#[derive(Debug, Deserialize, Serialize, Copy, Clone, PartialEq, Eq, PartialOrd, Ord, ValueEnum)]
pub enum RunningMode {
    Assess,
    Enforce,
}

/// Which system package format to download and install for self-updates.
#[derive(Debug, Default, Deserialize, Serialize, Copy, Clone, PartialEq, Eq, ValueEnum)]
pub enum PackageFormat {
    /// Auto-detect: prefer .deb when dpkg is available, otherwise .rpm.
    #[default]
    Auto,
    /// Debian / Ubuntu package (.deb), installed with dpkg.
    Deb,
    /// RPM package (.rpm), installed with rpm.
    Rpm,
    /// Windows installer (.msi), installed with msiexec.
    Msi,
}

/// Directory of regops' state: `/var/lib/regops`, or `%ProgramData%\regops`
/// on Windows.
pub fn state_dir() -> std::path::PathBuf {
    #[cfg(windows)]
    {
        let base = std::env::var("ProgramData").unwrap_or_else(|_| r"C:\ProgramData".to_string());
        std::path::Path::new(&base).join("regops")
    }
    #[cfg(not(windows))]
    {
        std::path::PathBuf::from("/var/lib/regops")
    }
}

/// `/etc/regops/config.toml`, or `%ProgramData%\regops\config.toml` on Windows.
pub fn default_config_path() -> String {
    #[cfg(windows)]
    {
        state_dir().join("config.toml").to_string_lossy().to_string()
    }
    #[cfg(not(windows))]
    {
        "/etc/regops/config.toml".to_string()
    }
}

/// Where compliance outcomes are reported.
#[derive(Debug, Default, Deserialize, Serialize, Copy, Clone, PartialEq, Eq, ValueEnum)]
pub enum Reporting {
    /// Standalone: outcomes are only logged.
    #[default]
    None,
    /// Pushed to regency's endpoint (configured in `[Regency]`).
    Regency,
}

/// How regops obtains the client certificate presented to regency.
#[derive(Debug, Default, Deserialize, Serialize, Copy, Clone, PartialEq, Eq, ValueEnum)]
pub enum TlsMode {
    /// Certificate and key issued by your own PKI, read from `cert_path` / `key_path`.
    #[default]
    ExternalCa,
    /// Issued by regency's built-in CA: enrolled once with a token, renewed automatically.
    BuiltInCa,
    /// Generated by regops; an admin approves its fingerprint in regency (pinning).
    SelfSigned,
}

pub enum GitAuthentication {
    None,
    WithToken(String),
}

pub fn init_tracing(system_integration: &SystemIntegrationConfig) {
    let fmt_layer = match system_integration.log_format {
        LogFormat::Raw => fmt::layer().boxed(),
        LogFormat::Json => fmt::layer().json().boxed(),
    };

    match tracing_subscriber::registry()
        .with(system_integration.log_level.to_tracing_level())
        .with(fmt_layer)
        .try_init()
    {
        Ok(()) => {}
        Err(details) => {
            warn!(%details, "Tracing global subscriber init failed");
            // A global subscriber is already installed from a previous retry
            // of run(); keep using it.
        }
    }
}
